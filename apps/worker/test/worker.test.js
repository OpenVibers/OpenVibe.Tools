'use strict';
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const http = require('node:http');
const { once } = require('node:events');
const WebSocket = require('../../gateway/node_modules/ws');
const { hash, sign, verify, bytes } = require('../server/protocol');
const { createRuntime } = require('../server/runtime');
const { createHub } = require('../../gateway/server/workers/hub');
(async () => {
    const { ownerGuard } = require('../../gateway/server/workers/owner');
    let admitted = false, status;
    const response = { set() {}, status(n) { status = n; return this; }, json() {} };
    const guard = ownerGuard({ verify: async token => token === 'owner-test' ? { username: 'owner' } : null, extractToken: r => r.token, origin: 'https://openvibe.tools', username: 'owner' });
    await guard({ token: 'owner-test', method: 'POST', headers: {} }, response, () => { admitted = true; });
    assert.equal(status, 403); assert.equal(admitted, false);
    await guard({ token: 'owner-test', method: 'POST', headers: { origin: 'https://openvibe.tools' } }, response, () => { admitted = true; });
    assert.equal(admitted, true);
    const token = crypto.randomBytes(32).toString('base64url'), id = `wrk_${crypto.randomBytes(12).toString('hex')}`;
    const headers = sign(token, id);
    assert(verify(hash(token), headers));
    assert(!verify(hash(token), { ...headers, 'x-worker-id': `wrk_${'0'.repeat(24)}` }));
    assert(!verify(hash(token), headers, Date.now() + 61000));
    assert.throws(() => bytes({ bytes: 'not base64' }));
    const registry = { defs: new Map([['img.process', { minFiles: 1, maxFiles: 1, timeoutMs: 1000, validate: () => null, run: async () => ({ files: [], data: { done: true } }) }]]), close: async () => {} };
    const runtime = createRuntime({ registry, slots: 1 });
    const job = { id: crypto.randomBytes(16).toString('hex'), type: 'img.process', input: {}, files: [{ bytes: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"/>').toString('base64') }] };
    await assert.rejects(runtime.run(job), /unsupported file/);
    await assert.rejects(runtime.run({ ...job, type: 'yt.download' }), /refused/);
    const dry = createRuntime({ registry, dry: true });
    assert.deepEqual(dry.status().capabilities, []);
    await assert.rejects(dry.run(job), /refused/);
    assert.equal(runtime.status().free, 1);
    const real = createRuntime({ slots: 1 });
    const sharp = require('../../img/node_modules/sharp');
    const png = await sharp({ create: { width: 2, height: 2, channels: 3, background: 'red' } }).png().toBuffer();
    const converted = await real.run({ ...job, input: { tool: 'convert', format: 'png' }, files: [{ bytes: png.toString('base64') }] });
    assert.equal(converted.files[0].mime, 'image/png');
    assert.equal((await sharp(Buffer.from(converted.files[0].bytes, 'base64')).metadata()).width, 2);
    await real.close();
    const store = { lookup: async key => key === id ? { token_hash: hash(token), location: 'home', draining: false } : null };
    const hub = createHub({ WebSocketServer: WebSocket.WebSocketServer, store });
    const server = http.createServer();
    server.on('upgrade', (req, sock, head) => hub.upgrade(req, sock, head));
    server.listen(0, '127.0.0.1'); await once(server, 'listening');
    const url = `ws://127.0.0.1:${server.address().port}/api/v1/workers/connect`;
    const ws = new WebSocket(url, { headers });
    await once(ws, 'open');
    ws.send(JSON.stringify({ type: 'status', capabilities: ['img.process'], slots: 1, free: 1, load: 0 }));
    await new Promise(r => setTimeout(r, 30));
    assert.equal(hub.stats()[0].free, 1);
    const replay = new WebSocket(url, { headers });
    await new Promise(resolve => replay.on('unexpected-response', (_req, res) => { assert.equal(res.statusCode, 401); res.resume(); replay.terminate(); resolve(); }).on('error', () => {}));
    const c = hub.connections.get(id);
    const pending = hub.dispatch(c, { type: 'img.process', input: {}, files: [], timeoutMs: 1000 });
    ws.terminate();
    await assert.rejects(pending, /disconnected/);
    hub.close(); await new Promise(r => server.close(r)); await runtime.close(); await dry.close();
    console.log('worker: signed channel, replay refusal, disconnect, dry mode, fetch/SVG refusal passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
